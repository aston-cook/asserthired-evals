import { GoldenCaseSchema } from './types.js';
import type { GoldenCase, GraderInput, GraderResult } from './types.js';

// Promptfoo cartesian-expands array-valued vars into one test per element, so
// golden cases travel through promptfoo as a single JSON-string var (caseJson)
// plus scalar convenience vars. This adapter decodes caseJson back into the
// GoldenCase shape the graders expect.

export interface PromptfooAssertionContext {
  test: { vars: Record<string, unknown> };
  providerResponse?: { latencyMs?: number };
}

export type InternalGrader = (input: GraderInput) => Promise<GraderResult>;

export type PromptfooAssertion = (
  output: string,
  context: PromptfooAssertionContext,
) => Promise<GraderResult>;

export function decodeCaseVars(vars: Record<string, unknown>): GoldenCase {
  const caseJson = vars['caseJson'];
  if (typeof caseJson !== 'string') {
    throw new Error(
      'Test vars are missing the caseJson var. Tests must be generated by scripts/promptfoo-tests.ts.',
    );
  }
  return GoldenCaseSchema.parse(JSON.parse(caseJson));
}

export function adapt(grader: InternalGrader): PromptfooAssertion {
  return async function promptfooAssertion(output, context) {
    return grader({
      output,
      test: { vars: decodeCaseVars(context.test.vars) },
      context: { latencyMs: context.providerResponse?.latencyMs },
    });
  };
}
